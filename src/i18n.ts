export function getInitialLang(): Lang {
  const stored = localStorage.getItem("shift.lang");
  if (stored === "en" || stored === "zh") return stored;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let value = messages[lang][key] ?? messages.en[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}

export function useI18n() {
  const [lang, setLangState] = useState<Lang>(getInitialLang);
  useEffect(() => {
    const sync = () => setLangState(getInitialLang());
    window.addEventListener("shift:lang", sync);
    window.addEventListener("storage", sync);
    return () => {
      window.removeEventListener("shift:lang", sync);
      window.removeEventListener("storage", sync);
    };
  }, []);
  const setLang = useCallback((next: Lang) => {
    localStorage.setItem("shift.lang", next);
    document.documentElement.lang = next === "zh" ? "zh-CN" : "en";
    window.dispatchEvent(new Event("shift:lang"));
    setLangState(next);
  }, []);
  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => translate(lang, key, vars),
    [lang],
  );
  return { lang, setLang, t };
}
